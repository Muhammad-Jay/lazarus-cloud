#!/usr/bin/env node
import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const root = resolve(__dirname, '..', '..');
const tokensJsonPath = resolve(root, 'packages', 'tokens', 'src', 'tokens.json');
const contractsSchemaPath = resolve(root, 'packages', 'contracts', 'src', 'schema', 'interaction.schema.json');
const outCss = resolve(root, 'packages', 'tokens', 'src', 'generated', 'tokens.css');
const outTs = resolve(root, 'packages', 'tokens', 'src', 'generated', 'tokens.ts');

function sortKeys(obj) {
  if (Array.isArray(obj)) return obj;
  if (obj && typeof obj === 'object') {
    const out = {};
    for (const k of Object.keys(obj).sort()) out[k] = sortKeys(obj[k]);
    return out;
  }
  return obj;
}

const tokens = JSON.parse(readFileSync(tokensJsonPath, 'utf8'));
const schema = JSON.parse(readFileSync(contractsSchemaPath, 'utf8'));
const colorRoleEnum = schema?.$defs?.colorRole?.enum;
if (!Array.isArray(colorRoleEnum) || colorRoleEnum.length === 0) {
  throw new Error('colorRole enum missing from interaction schema');
}
const tokenRoles = Object.keys(tokens.colorRoles);
if (tokenRoles.length !== colorRoleEnum.length) {
  throw new Error(`colorRoles count mismatch: tokens=${tokenRoles.length} schema=${colorRoleEnum.length}`);
}
for (const r of colorRoleEnum) {
  if (!(r in tokens.colorRoles)) throw new Error(`colorRoles missing role ${r}`);
}
for (const r of tokenRoles) {
  if (!colorRoleEnum.includes(r)) throw new Error(`colorRoles has extra role ${r}`);
}

// Build CSS
const cssLines = [];
cssLines.push('/* generated by tools/codegen/generate-tokens.mjs — do not edit */');
cssLines.push(':root {');
cssLines.push('  color-scheme: light;');

// mono
for (const [k, v] of Object.entries(tokens.palette.mono)) {
  cssLines.push(`  --color-mono-${k}: ${v};`);
}

// semantic - light
const sem = tokens.semantic;
function addSemLight(prefix, obj) {
  for (const [k, v] of Object.entries(obj)) {
    if (k === 'dark') continue;
    if (Array.isArray(v)) {
      v.forEach((val, i) => {
        cssLines.push(`  --color-${prefix}-${k}-${i}: ${val};`);
      });
    } else if (typeof v === 'object' && v !== null) {
      for (const [kk, vv] of Object.entries(v)) {
        if (typeof vv === 'string') cssLines.push(`  --color-${prefix}-${k}-${kk}: ${vv};`);
      }
    } else if (typeof v === 'string') {
      cssLines.push(`  --color-${prefix}-${k}: ${v};`);
    } else if (typeof v === 'number') {
      cssLines.push(`  --color-${prefix}-${k}: ${v};`);
    }
  }
}
addSemLight('surface', sem.surface);
addSemLight('panel', sem.panel);
addSemLight('text', sem.text);
addSemLight('border', sem.border);
addSemLight('action', sem.action);
addSemLight('status', sem.status);
addSemLight('brand', sem.brand);
addSemLight('glass', sem.glass);
addSemLight('background', sem.background);

// shadows
for (const [k, v] of Object.entries(tokens.shadow)) {
  if (k === 'dark') continue;
  cssLines.push(`  --shadow-${k}: ${v};`);
}
// radius
for (const [k, v] of Object.entries(tokens.radius)) {
  if (k === 'dark') continue;
  cssLines.push(`  --radius-${k}: ${v};`);
}
// spacing
for (const [k, v] of Object.entries(tokens.spacing)) {
  cssLines.push(`  --space-${k}: ${v};`);
}
// motion
for (const [k, v] of Object.entries(tokens.motion.duration || {})) {
  cssLines.push(`  --motion-duration-${k}: ${v};`);
}
for (const [k, v] of Object.entries(tokens.motion.ease || {})) {
  cssLines.push(`  --motion-ease-${k}: ${v};`);
}
// z
for (const [k, v] of Object.entries(tokens.zIndex || {})) {
  cssLines.push(`  --z-${k}: ${v};`);
}
// color roles
for (const [role, target] of Object.entries(tokens.colorRoles)) {
  cssLines.push(`  --color-role-${role}: var(--color-${target.replace(/\./g, '-')});`);
}
cssLines.push('}');
cssLines.push('');

// dark
cssLines.push('.dark {');
cssLines.push('  color-scheme: dark;');
function addSemDark(prefix, obj) {
  const d = obj.dark || {};
  for (const [k, v] of Object.entries(d)) {
    if (Array.isArray(v)) {
      v.forEach((val, i) => {
        cssLines.push(`  --color-${prefix}-${k}-${i}: ${val};`);
      });
    } else if (typeof v === 'object' && v !== null) {
      for (const [kk, vv] of Object.entries(v)) {
        if (typeof vv === 'string') cssLines.push(`  --color-${prefix}-${k}-${kk}: ${vv};`);
      }
    } else if (typeof v === 'string') {
      cssLines.push(`  --color-${prefix}-${k}: ${v};`);
    } else if (typeof v === 'number') {
      cssLines.push(`  --color-${prefix}-${k}: ${v};`);
    }
  }
}
addSemDark('surface', sem.surface);
addSemDark('panel', sem.panel);
addSemDark('text', sem.text);
addSemDark('border', sem.border);
addSemDark('action', sem.action);
addSemDark('status', sem.status);
addSemDark('brand', sem.brand);
addSemDark('glass', sem.glass);
addSemDark('background', sem.background);
for (const [k, v] of Object.entries(tokens.shadow.dark || {})) {
  cssLines.push(`  --shadow-${k}: ${v};`);
}
cssLines.push('}');
writeFileSync(outCss, cssLines.join('\n') + '\n', 'utf8');

// TS
const tsLines = [];
tsLines.push('/* generated by tools/codegen/generate-tokens.mjs — do not edit */');
tsLines.push('export type ColorRole =');
colorRoleEnum.forEach((r, i) => {
  tsLines.push(`  | '${r}'${i === colorRoleEnum.length - 1 ? ';' : ''}`);
});
tsLines.push('');
tsLines.push('export const colorRoles = {');
for (const r of colorRoleEnum) {
  tsLines.push(`  ${r}: 'var(--color-role-${r})',`);
}
tsLines.push('} as const satisfies Record<ColorRole, string>;');
tsLines.push('');
tsLines.push('export const palette = ' + JSON.stringify(sortKeys(tokens.palette), null, 2) + ' as const;');
tsLines.push('export const semantic = ' + JSON.stringify(sortKeys(tokens.semantic), null, 2) + ' as const;');
tsLines.push('export const shadow = ' + JSON.stringify(sortKeys({ light: tokens.shadow, dark: tokens.shadow.dark }), null, 2).replace('"light":', 'light:').replace('"dark":', 'dark:').replace(/"([a-zA-Z0-9_-]+)":/g, (m, p1) => (p1 === 'light' || p1 === 'dark' ? m : `"${p1}":`)) + ' as const;');
tsLines.push('export const radius = ' + JSON.stringify(sortKeys(tokens.radius), null, 2) + ' as const;');
tsLines.push('export const spacing = ' + JSON.stringify(sortKeys(tokens.spacing), null, 2) + ' as const;');
tsLines.push('export const motion = ' + JSON.stringify(sortKeys(tokens.motion), null, 2) + ' as const;');
tsLines.push('export const zIndex = ' + JSON.stringify(sortKeys(tokens.zIndex || {}), null, 2) + ' as const;');
writeFileSync(outTs, tsLines.join('\n') + '\n', 'utf8');

console.log('generated tokens.css and tokens.ts');
